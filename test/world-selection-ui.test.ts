import assert from 'node:assert/strict';
import { EnvironmentSelectModal } from '../src/ui/EnvironmentSelectModal';
import { ProgressionManager } from '../src/progression/ProgressionManager';
import { UpgradeManager } from '../src/player/UpgradeManager';

const data = new Map<string, string>();
(globalThis as any).localStorage = { getItem: (key: string) => data.get(key) ?? null, setItem: (key: string, value: string) => data.set(key, value), removeItem: (key: string) => data.delete(key) };
const feedback = { textContent: '', classList: { remove() {} } };
(globalThis as any).document = { getElementById: (id: string) => id === 'env-feedback' ? feedback : null };
const progression = ProgressionManager.getInstance(), wallet = UpgradeManager.getInstance();
const before = progression.getSelectedTheme();
let closed = 0;
const modal = Object.assign(Object.create(EnvironmentSelectModal.prototype), { selectedPreference: 'ORBITAL_HALO', hide: () => closed++ }) as any;
modal.applySelection();
assert.equal(progression.getSelectedTheme(), before);
assert.equal(closed, 0);
assert.match(feedback.textContent, /locked/);
wallet.setCoins(10000);
assert.equal(progression.purchaseTheme('ORBITAL_HALO').success, true);
const afterPurchase = wallet.getCoins();
modal.applySelection();
assert.equal(progression.getSelectedTheme(), 'ORBITAL_HALO');
assert.equal(wallet.getCoins(), afterPurchase, 'equipping never purchases again');
assert.equal(closed, 1);
modal.selectedPreference = 'DYNAMIC';
modal.applySelection();
assert.equal(progression.getSelectedTheme(), 'DYNAMIC');
assert.equal(wallet.getCoins(), afterPurchase);
assert.equal(closed, 2);
console.log('VERDICT: PASS — locked selection rejected, existing purchase unlocks equip, Dynamic retained, no duplicate spending');
